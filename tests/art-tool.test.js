import test from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { ASSET_MANIFEST } from "../src/assets/manifest.js";

const root = fileURLToPath(new URL("..", import.meta.url));
const tool = resolve(root, "tools/generate-placeholders.mjs");

/** Runs the placeholder generator with arguments; returns its stdout. */
function run(args) {
  return execFileSync(process.execPath, [tool, ...args], {
    cwd: root,
    encoding: "utf8",
  });
}

test("--out writes the placeholders somewhere other than assets/", () => {
  const outDir = mkdtempSync(join(tmpdir(), "afterbuy-art-"));
  try {
    // A sentinel: the real art must not be touched by an --out run.
    const sentinel = resolve(root, ASSET_MANIFEST.plant.file);
    const before = readFileSync(sentinel);

    const output = run(["--out", outDir]);
    assert.match(output, /Generated 21 placeholder images/);

    for (const entry of Object.values(ASSET_MANIFEST)) {
      const written = readFileSync(join(outDir, entry.file.replace(/^assets\//, "")));
      const width = written.readUInt32BE(16);
      const height = written.readUInt32BE(20);
      assert.equal(width, entry.width, `${entry.file} width`);
      assert.equal(height, entry.height, `${entry.file} height`);
    }

    assert.deepEqual(readFileSync(sentinel), before, "assets/ must be untouched");
  } finally {
    rmSync(outDir, { recursive: true, force: true });
  }
});

test("hand-drawn art is kept unless --force is passed", () => {
  const outDir = mkdtempSync(join(tmpdir(), "afterbuy-art-"));
  try {
    run(["--only", "plant", "--out", outDir]);
    const target = join(outDir, "furniture/plant.png");
    const handDrawn = readFileSync(resolve(root, ASSET_MANIFEST.player_idle.file));
    writeFileSync(target, handDrawn);

    const keptRun = run(["--only", "plant", "--out", outDir]);
    assert.match(keptRun, /Kept 1 file/);
    assert.deepEqual(readFileSync(target), handDrawn, "the replacement was overwritten");

    run(["--only", "plant", "--out", outDir, "--force"]);
    assert.notDeepEqual(readFileSync(target), handDrawn, "--force should regenerate");
    assert.equal(readFileSync(target).readUInt32BE(16), 44, "regenerated plant width");
  } finally {
    rmSync(outDir, { recursive: true, force: true });
  }
});

test("a deleted placeholder is restored, and unknown IDs still fail", () => {
  const outDir = mkdtempSync(join(tmpdir(), "afterbuy-art-"));
  try {
    const target = join(outDir, "items/parcel.png");
    run(["--only", "parcel", "--out", outDir]);
    const original = readFileSync(target);
    rmSync(target);
    run(["--only", "parcel", "--out", outDir]);
    assert.deepEqual(readFileSync(target), original, "a missing placeholder is rewritten");

    assert.throws(() => run(["--only", "definitely_not_an_asset", "--out", outDir]), /No placeholder matches/);
  } finally {
    rmSync(outDir, { recursive: true, force: true });
  }
});

test("the shipped hand-drawn files are not byte-identical to the generator", () => {
  // Guards the inventory: these are the IDs whose art is imported. If one is
  // regenerated by accident the docs' "imported" status becomes a lie.
  const imported = ["player_idle", "player_walk", "floor_tile", "wall_tile", "rug"];
  const outDir = mkdtempSync(join(tmpdir(), "afterbuy-art-"));
  try {
    run(["--out", outDir]);
    for (const id of imported) {
      const entry = ASSET_MANIFEST[id];
      const disk = readFileSync(resolve(root, entry.file));
      const generated = readFileSync(join(outDir, entry.file.replace(/^assets\//, "")));
      assert.notDeepEqual(disk, generated, `${id} looks like the generator's output again`);
    }
  } finally {
    rmSync(outDir, { recursive: true, force: true });
  }
});
